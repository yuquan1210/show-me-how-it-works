export function applyDemoChange(model) {
  const copy = structuredClone(model);
  const n = copy.nodes.find((n) => n.id === "orders");
  n.status = "modified";
  n.decisions.push("Duplicate checkout → return the existing order");
  n.change = "Added a duplicate-checkout check before reserving stock.";
  n.summary =
    "Coordinates checkout and prevents duplicate orders before reserving stock, requesting payment, and saving the result.";
  copy.nodes.push(
    node(
      "deduplicate",
      "Checkout guard",
      "service",
      "shield-check",
      "Recognizes repeated checkout requests to avoid duplicate orders and charges.",
      ["Checkout request identifier"],
      ["Existing order or permission to continue"],
      [
        "Already processed → return the existing order",
        "New request → allow checkout",
      ],
      ["Records checkout request identifiers"],
      ["Check duplicate request"],
    ),
  );
  copy.nodes.at(-1).status = "added";
  copy.edges.push(["orders", "deduplicate"]);
  copy.functionEdges.push(["orders#0", "deduplicate#0"]);
  copy.workflows[0].nodes.push("deduplicate");
  copy.updated = Date.now();
  return copy;
}

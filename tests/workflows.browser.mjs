  assert.ok(ids.some(id=>id.includes('#calculateTotal:')));assert.ok(!ids.some(id=>id.includes('#refund:')));
  await selectNode('src/pricing.service.ts#calculateTotal:0');
  const pricing=await structure();assert.match(pricing,/2500/);assert.match(pricing,/at least 4/);assert.match(pricing,/0.9/);assert.match(pricing,/500/);assert.match(pricing,/WELCOME/);
  assert.ok(!pricing.includes('Implementation detail omitted'));
  await page.screenshot({path:'test-results/workflow-pricing.png'});
  await page.locator('#close-inspector').click();
  const chargeEdge=page.getByRole('button',{name:'Explain Book to Charge',exact:true});
  await chargeEdge.focus();await page.keyboard.press('Enter');
  await expect(page.locator('#inspector')).toContainText('release seats');
  await page.locator('#close-edge').click();
  const priceEdge=page.getByRole('button',{name:'Explain Book to Calculate Total',exact:true});
  await priceEdge.focus();await page.keyboard.press('Enter');
  await expect(page.locator('#inspector')).toContainText('No local catch');
  await page.locator('#close-edge').click();
  await page.locator('[data-level="architecture"]').click();await selectNode('component:booking');
  const booking=await structure();assert.ok(!booking.includes('refund'));
  await page.setViewportSize({width:1024,height:768});
  await expect(page.locator('#detail-structure-tab')).toBeVisible();
  await page.screenshot({path:'test-results/workflow-narrow.png'});
  const size=await page.evaluate(()=>({body:document.body.scrollWidth,viewport:innerWidth}));assert.ok(size.body<=size.viewport+1);
  await page.setViewportSize({width:1440,height:1000});
